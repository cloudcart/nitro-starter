// ESLint for the storefront: TypeScript, React, hooks and accessibility rules. Formatting belongs
// to Prettier, so `eslint-config-prettier` comes last and turns the stylistic rules off.
import js from '@eslint/js';
import comments from '@eslint-community/eslint-plugin-eslint-comments/configs';
import eslintReact from '@eslint-react/eslint-plugin';
import prettier from 'eslint-config-prettier';
import jsxA11y from 'eslint-plugin-jsx-a11y-x';
import reactHooks from 'eslint-plugin-react-hooks';
import {defineConfig} from 'eslint/config';
import globals from 'globals';
import starter from './scripts/eslint-no-literal-text.mjs';
import tseslint from 'typescript-eslint';

const reactConfig = eslintReact.configs['recommended-typescript'];

// The hooks rules come from React's own plugin, the whole `recommended-latest` set: the two classic
// rules and the React Compiler's. `@eslint-react` has rules of the same names; they are turned off
// so a problem is reported once, by React's plugin.
const duplicateHooksRules = Object.fromEntries(
  Object.keys(reactHooks.configs.flat['recommended-latest'].rules)
    .map((rule) => rule.replace('react-hooks/', ''))
    .filter((rule) => rule in reactConfig.plugins['@eslint-react'].rules)
    .map((rule) => [`@eslint-react/${rule}`, 'off']),
);

export default defineConfig(
  {
    ignores: [
      '**/node_modules/',
      'build/',
      'dist/',
      '.react-router/',
      // Generated by `npm run codegen`.
      '**/*.generated.d.ts',
    ],
  },
  js.configs.recommended,
  tseslint.configs.recommended,
  comments.recommended,
  {
    languageOptions: {
      globals: {...globals.browser, ...globals.node},
    },
    rules: {
      'no-console': ['warn', {allow: ['warn', 'error']}],
      '@eslint-community/eslint-comments/no-unused-disable': 'error',
      '@eslint-community/eslint-comments/require-description': 'error',
      // A leading underscore marks a name that is deliberately unused: a rest-destructuring
      // remainder or a parameter an interface requires.
      '@typescript-eslint/no-unused-vars': [
        'error',
        {
          argsIgnorePattern: '^_',
          varsIgnorePattern: '^_',
          destructuredArrayIgnorePattern: '^_',
          ignoreRestSiblings: true,
        },
      ],
      // `interface X extends Y {}` is how the app extends Nitrogen's types (declaration merging,
      // see `app/lib/context.ts`); other empty object types stay errors.
      '@typescript-eslint/no-empty-object-type': ['error', {allowInterfaces: 'with-single-extends'}],
    },
  },
  {
    // Type-aware rules: an unhandled promise in a loader or an action fails silently.
    files: ['**/*.{ts,tsx}'],
    languageOptions: {
      parserOptions: {projectService: true, tsconfigRootDir: import.meta.dirname},
    },
    rules: {
      '@typescript-eslint/no-floating-promises': 'error',
      '@typescript-eslint/no-misused-promises': 'error',
    },
  },
  {
    files: ['**/*.{ts,tsx}'],
    extends: [reactConfig],
    plugins: {'react-hooks': reactHooks, starter},
    rules: {
      // A visitor's text comes from the translations (B-203).
      'starter/no-literal-text': 'error',
      ...duplicateHooksRules,
      ...reactHooks.configs.flat['recommended-latest'].rules,
    },
  },
  {
    files: ['**/*.tsx'],
    extends: [jsxA11y.configs.recommended],
    rules: {
      // The form controls of `~/components/ui/Field` render an input, so a label around one is labelled.
      'jsx-a11y-x/label-has-associated-control': [
        'error',
        {controlComponents: ['Input', 'Select', 'Textarea', 'Checkbox', 'Radio'], depth: 3},
      ],
    },
  },
  {
    // Every icon comes from the icon set, so the set is changed in one file.
    files: ['app/**/*.{ts,tsx}'],
    ignores: ['app/components/ui/icons.tsx'],
    rules: {
      'no-restricted-imports': [
        'error',
        {patterns: [{group: ['@heroicons/*'], message: 'Use the icons in `~/components/ui/icons`.'}]},
      ],
    },
  },
  prettier,
);
